package com.android.server.ichthys;

import android.content.Context;
import android.content.om.FabricatedOverlay;
import android.content.om.OverlayIdentifier;
import android.content.om.OverlayInfo;
import android.content.om.OverlayManager;
import android.content.om.OverlayManagerTransaction;
import android.content.res.Resources;
import android.os.UserHandle;
import android.util.Slog;
import android.util.TypedValue;

/**
 * Turns theme.shape.*, theme.font.* and theme.surface into resource overrides with fabricated
 * overlays (owned by "android", so they survive reboots in OverlayManagerService's state and need
 * no APK). Colours are not overlaid here: the palette (Monet + the Shoal ramp and the
 * {@code ichthys_*} colour tokens, {@code ichthys_surface_style}/{@code _levels}) is generated by
 * the theming service into {@code android:dynamic_<user>}; see ShoalPalette.
 *
 * <p>{@code android:ichthys_theme_tokens} (target android):
 * <ul>
 *   <li>theme.shape.radius set: {@code dimen/ichthys_radius} = radius,
 *       {@code ichthys_radius_small} = max(4, radius/2); {@code config_dialogCornerRadius},
 *       {@code config_bottomDialogCornerRadius}, {@code system_app_widget_background_radius} =
 *       radius; {@code config_buttonCornerRadius} = radius/2 (100dp for pill ends).</li>
 *   <li>always: {@code string/ichthys_font_display}, {@code ichthys_font_text},
 *       {@code ichthys_font_mono} = the effective theme.font.* families.</li>
 *   <li>theme.surface != stock and no font overlay package (theme.font.body) chosen:
 *       {@code config_bodyFontFamily}/{@code Medium} = text face,
 *       {@code config_headlineFontFamily}/{@code Medium} = display face, so the whole system
 *       (DeviceDefault/Material text appearances) speaks the theme's type.</li>
 * </ul>
 * <p>{@code android:ichthys_theme_shape_sysui} (target SystemUI, radius set): {@code dimen/
 * qs_corner_radius}, {@code notification_corner_radius} = radius.
 */
final class ThemeApplier {
    private static final String TAG = "IchthysConfig";
    private static final String OWNER = "android";
    private static final String ANDROID_OVERLAY = "ichthys_theme_tokens";
    /** The pre-tokens name of the android overlay; removed when found. */
    private static final String LEGACY_ANDROID_OVERLAY = "ichthys_theme_shape";
    private static final String SYSUI_OVERLAY = "ichthys_theme_shape_sysui";
    private static final String SYSUI = "com.android.systemui";
    private static final int PILL_DP = 100;

    /** Everything the token overlays are built from (effective values, defaults resolved). */
    static final class Tokens {
        /** Corner radius in dp, or null for the stock shapes. */
        final Long radiusDp;
        /** "rounded", "pill" or "squircle". */
        final String shapeStyle;
        final String fontDisplay;
        final String fontText;
        final String fontMono;
        /** theme.surface == "stock": leave the system fonts alone. */
        final boolean stock;
        /** theme.font.body names a font overlay package, which owns config_*FontFamily. */
        final boolean fontPackage;

        Tokens(Long radiusDp, String shapeStyle, String fontDisplay, String fontText,
                String fontMono, boolean stock, boolean fontPackage) {
            this.radiusDp = radiusDp;
            this.shapeStyle = shapeStyle != null ? shapeStyle : "rounded";
            this.fontDisplay = emptyToNull(fontDisplay);
            this.fontText = emptyToNull(fontText);
            this.fontMono = emptyToNull(fontMono);
            this.stock = stock;
            this.fontPackage = fontPackage;
        }

        /** Whether the android overlay has any entry at all. */
        boolean hasAndroidValues() {
            return radiusDp != null || fontDisplay != null || fontText != null
                    || fontMono != null;
        }

        boolean systemFonts() {
            return !stock && !fontPackage;
        }

        int radius() {
            return radiusDp.intValue();
        }

        int radiusSmall() {
            return Math.max(4, radius() / 2);
        }

        int button() {
            return "pill".equals(shapeStyle) ? PILL_DP : Math.max(4, radius() / 2);
        }

        @Override
        public String toString() {
            return "radius=" + radiusDp + " style=" + shapeStyle + " display=" + fontDisplay
                    + " text=" + fontText + " mono=" + fontMono + " stock=" + stock
                    + " fontPackage=" + fontPackage;
        }
    }

    private final Context mContext;

    ThemeApplier(Context context) {
        mContext = context;
    }

    /**
     * Builds and commits the token overlays for {@code userId} (also enabled for the system user,
     * which SystemUI runs as).
     *
     * @param onlyIfStale skip the commit when the resources on screen already match (boot path,
     *                    so a normal boot does not re-register overlays and churn configuration)
     */
    void applyTokens(Tokens t, int userId, boolean onlyIfStale) {
        final OverlayManager om = mContext.getSystemService(OverlayManager.class);
        if (om == null) {
            Slog.w(TAG, "OverlayManager unavailable, tokens not applied");
            return;
        }
        final OverlayIdentifier androidId = new OverlayIdentifier(OWNER, ANDROID_OVERLAY);
        final OverlayIdentifier legacyId = new OverlayIdentifier(OWNER, LEGACY_ANDROID_OVERLAY);
        final OverlayIdentifier sysuiId = new OverlayIdentifier(OWNER, SYSUI_OVERLAY);
        final UserHandle user = UserHandle.of(userId);

        if (onlyIfStale && isApplied(om, t, userId)) {
            Slog.i(TAG, "user " + userId + " tokens up to date");
            return;
        }

        final OverlayManagerTransaction.Builder tx = new OverlayManagerTransaction.Builder();
        // Unregistering an overlay that was never registered fails the whole transaction, so
        // only remove what exists.
        if (exists(om, legacyId, user)) {
            tx.unregisterFabricatedOverlay(legacyId);
        }

        final FabricatedOverlay android;
        FabricatedOverlay sysui = null;
        try {
            // The legacy Builder only takes int data types (16..31); dimensions and strings need
            // the FRRO overloads on FabricatedOverlay itself.
            android = new FabricatedOverlay(ANDROID_OVERLAY, "android");
            android.setOwningPackage(OWNER);
            if (t.radiusDp != null) {
                setDp(android, "android:dimen/ichthys_radius", t.radius());
                setDp(android, "android:dimen/ichthys_radius_small", t.radiusSmall());
                setDp(android, "android:dimen/config_dialogCornerRadius", t.radius());
                setDp(android, "android:dimen/config_bottomDialogCornerRadius", t.radius());
                setDp(android, "android:dimen/system_app_widget_background_radius", t.radius());
                setDp(android, "android:dimen/config_buttonCornerRadius", t.button());
                sysui = new FabricatedOverlay(SYSUI_OVERLAY, SYSUI);
                sysui.setOwningPackage(OWNER);
                setDp(sysui, SYSUI + ":dimen/qs_corner_radius", t.radius());
                setDp(sysui, SYSUI + ":dimen/notification_corner_radius", t.radius());
            }
            setString(android, "android:string/ichthys_font_display", t.fontDisplay);
            setString(android, "android:string/ichthys_font_text", t.fontText);
            setString(android, "android:string/ichthys_font_mono", t.fontMono);
            if (t.systemFonts()) {
                setString(android, "android:string/config_bodyFontFamily", t.fontText);
                setString(android, "android:string/config_bodyFontFamilyMedium", t.fontText);
                setString(android, "android:string/config_headlineFontFamily", t.fontDisplay);
                setString(android, "android:string/config_headlineFontFamilyMedium",
                        t.fontDisplay);
            }
        } catch (RuntimeException e) {
            // Tokens are cosmetic: never let them fail the whole generation.
            Slog.w(TAG, "token overlay not built", e);
            return;
        }

        if (t.hasAndroidValues()) {
            tx.registerFabricatedOverlay(android);
            enable(tx, android.getIdentifier(), userId);
        } else if (exists(om, androidId, user)) {
            tx.unregisterFabricatedOverlay(androidId);
        }
        if (sysui != null) {
            tx.registerFabricatedOverlay(sysui);
            enable(tx, sysui.getIdentifier(), userId);
        } else if (exists(om, sysuiId, user)) {
            tx.unregisterFabricatedOverlay(sysuiId);
        }
        try {
            om.commit(tx.build());
            Slog.i(TAG, "user " + userId + " tokens applied: " + t);
        } catch (RuntimeException e) {
            Slog.w(TAG, "token overlay commit failed", e);
        }
    }

    private static void enable(OverlayManagerTransaction.Builder tx, OverlayIdentifier id,
            int userId) {
        tx.setEnabled(id, true, userId);
        if (userId != UserHandle.USER_SYSTEM) {
            tx.setEnabled(id, true, UserHandle.USER_SYSTEM);
        }
    }

    private static boolean exists(OverlayManager om, OverlayIdentifier id, UserHandle user) {
        try {
            return om.getOverlayInfo(id, user) != null;
        } catch (RuntimeException e) {
            return false;
        }
    }

    private static boolean enabled(OverlayManager om, OverlayIdentifier id, UserHandle user) {
        try {
            final OverlayInfo info = om.getOverlayInfo(id, user);
            return info != null && info.isEnabled();
        } catch (RuntimeException e) {
            return false;
        }
    }

    /** Whether the overlays for {@code t} are registered, enabled and resolved for the user. */
    private boolean isApplied(OverlayManager om, Tokens t, int userId) {
        final UserHandle user = UserHandle.of(userId);
        if (exists(om, new OverlayIdentifier(OWNER, LEGACY_ANDROID_OVERLAY), user)
                || t.hasAndroidValues()
                        != enabled(om, new OverlayIdentifier(OWNER, ANDROID_OVERLAY), user)
                || (t.radiusDp != null)
                        != enabled(om, new OverlayIdentifier(OWNER, SYSUI_OVERLAY), user)) {
            return false;
        }
        try {
            final Resources res = mContext.createContextAsUser(user, 0).getResources();
            if (differs(t.fontDisplay,
                    res.getString(com.android.internal.R.string.ichthys_font_display))
                    || differs(t.fontText,
                    res.getString(com.android.internal.R.string.ichthys_font_text))
                    || differs(t.fontMono,
                    res.getString(com.android.internal.R.string.ichthys_font_mono))) {
                return false;
            }
            if (t.systemFonts() && t.fontText != null && !t.fontText.equals(res.getString(
                    com.android.internal.R.string.config_bodyFontFamily))) {
                return false;
            }
            if (t.radiusDp != null) {
                final TypedValue v = new TypedValue();
                res.getValue(com.android.internal.R.dimen.ichthys_radius, v, true);
                if (v.type != TypedValue.TYPE_DIMENSION
                        || v.getComplexUnit() != TypedValue.COMPLEX_UNIT_DIP
                        || TypedValue.complexToFloat(v.data) != t.radius()) {
                    return false;
                }
            }
            return true;
        } catch (RuntimeException e) {
            return false;
        }
    }

    private static void setDp(FabricatedOverlay overlay, String resourceName, int dp) {
        overlay.setResourceValue(resourceName, (float) dp, TypedValue.COMPLEX_UNIT_DIP,
                null /* configuration */);
    }

    /** Sets a string; empty/null values are skipped so the resource keeps its default. */
    private static void setString(FabricatedOverlay overlay, String resourceName, String value) {
        if (value == null || value.isEmpty()) {
            return;
        }
        overlay.setResourceValue(resourceName, TypedValue.TYPE_STRING, value,
                null /* configuration */);
    }

    /** A wanted value (null = keep the default, anything matches) that is not on screen. */
    private static boolean differs(String wanted, String actual) {
        return wanted != null && !wanted.equals(actual);
    }

    private static String emptyToNull(String s) {
        return s == null || s.isEmpty() ? null : s;
    }
}
